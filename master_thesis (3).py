# Realistic simulation: rebalance back to target weights every December.
# Compares buy-and-hold vs annually rebalanced for the 60/30 + Metals portfolio.

def rebalanced_portfolio(returns_df, weights_dict, freq='Y'):
    """
    Simulate a rebalanced portfolio.
    weights_dict: {column_name: weight}
    freq: 'Y' = annual, 'Q' = quarterly
    """
    cols    = list(weights_dict.keys())
    w0      = np.array([weights_dict[c] for c in cols])
    ret_sub = returns_df[cols].dropna()

    portfolio_vals = [1.0]
    current_w      = w0.copy()

    rebal_dates = ret_sub.resample(freq).last().index

    for date, daily_ret in ret_sub.iterrows():
        # Grow weights by daily returns
        current_w = current_w * (1 + daily_ret[cols].values)
        total_val  = current_w.sum()
        portfolio_vals.append(total_val)

        # Rebalance on period-end dates
        if date in rebal_dates:
            current_w = w0 * total_val  # reset to target weights

    series = pd.Series(portfolio_vals[1:], index=ret_sub.index)
    return series.pct_change().fillna(0)

