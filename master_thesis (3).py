def compute_metrics(returns_series, rf=0.02):
    """Compute all key academic portfolio metrics."""
    # CAGR geometrico corretto
    cagr      = (1 + returns_series).prod() ** (252 / len(returns_series)) - 1
    vol       = returns_series.std()  * np.sqrt(252)
    sharpe    = (cagr - rf) / vol

    # Sortino: downside deviation corretta
    neg       = returns_series.copy()
    neg[neg > 0] = 0
    d_dev     = neg.std() * np.sqrt(252)
    sortino   = (cagr - rf) / d_dev

    # Maximum Drawdown
    cum         = (1 + returns_series).cumprod()
    rolling_max = cum.cummax()
    drawdown    = (cum / rolling_max) - 1
    mdd         = drawdown.min()

    # Calmar Ratio (CAGR / |MDD|)
    calmar = cagr / abs(mdd)

    # CVaR al 95% (Expected Shortfall)
    var_95  = np.percentile(returns_series.dropna(), 5)
    cvar_95 = returns_series[returns_series <= var_95].mean()

    return {
        'Ann. Return (%)':     round(cagr  * 100, 2),
        'Ann. Volatility (%)': round(vol   * 100, 2),
        'Sharpe Ratio':        round(sharpe,       3),
        'Sortino Ratio':       round(sortino,       3),
        'Max Drawdown (%)':    round(mdd   * 100,  2),
        'Calmar Ratio':        round(calmar,        3),
        'CVaR 95% (daily %)':  round(cvar_95 * 100, 3),
    }

