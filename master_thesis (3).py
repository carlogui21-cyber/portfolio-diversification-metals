def regime_metrics(regime_date_list, portfolio_returns_df):
    """Extract returns for a regime defined by multiple date windows."""
    frames = []
    for start, end in regime_date_list:
        mask = (portfolio_returns_df.index >= start) & (portfolio_returns_df.index <= end)
        frames.append(portfolio_returns_df.loc[mask])
    regime_df = pd.concat(frames)
    # Annualise
    ann_ret = regime_df.mean() * 252 * 100
    ann_vol = regime_df.std()  * np.sqrt(252) * 100
    sharpe  = (regime_df.mean() * 252 - 0.02) / (regime_df.std() * np.sqrt(252))
    return ann_ret, ann_vol, sharpe

