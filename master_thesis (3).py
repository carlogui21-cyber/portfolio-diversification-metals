# --- Test 4: Jobson-Korkie Sharpe Ratio difference test ---
# Tests whether the Sharpe of portfolio A is STATISTICALLY different from B.
def jobson_korkie_test(r1, r2, rf_daily=0.02/252):
    """
    Jobson & Korkie (1981) test for equality of Sharpe Ratios.
    Returns: z-statistic, p-value (two-tailed).
    Reference: Jobson, J.D. & Korkie, B.M. (1981), JFE.
    """
    n   = len(r1)
    mu1, mu2 = r1.mean() - rf_daily, r2.mean() - rf_daily
    s1,  s2  = r1.std(),  r2.std()
    sr1, sr2 = mu1 / s1,  mu2 / s2

    s12 = np.cov(r1, r2)[0, 1]
    theta = (1/n) * (2 * s1**2 * s2**2
                     - 2 * s1 * s2 * s12
                     + 0.5 * mu1**2 * s2**2
                     + 0.5 * mu2**2 * s1**2
                     - (mu1 * mu2 / (s1 * s2)) * s12**2)
    z = (sr1 - sr2) / np.sqrt(theta)
    p = 2 * (1 - stats.norm.cdf(abs(z)))
    return z, p

print("\n--- Test 4: Jobson-Korkie Test — Sharpe Ratio Equality ---")
